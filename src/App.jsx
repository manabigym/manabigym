/* 表紙画像のキャッシュ(同じ参考書を何度も検索しないように) */
const bookImageCache = {};

function BookCard({ book }) {
  const s = SUBJECT_GROUPS[book.subject];
  const u = USAGE_GROUPS[book.usage] || { color: INK_SOFT, soft: "#F4ECDC" };
  const [imgUrl, setImgUrl] = useState(bookImageCache[book.id]?.url || null);
  const [imgStatus, setImgStatus] = useState(bookImageCache[book.id]?.status || "loading"); // loading | found | none
  // 参考書名+科目で検索精度を上げる
  const searchTerm = `${book.title} ${book.subjectDetail} 参考書`;
  const amazonUrl = `https://www.amazon.co.jp/s?k=${encodeURIComponent(searchTerm)}`;
  const googleUrl = `https://www.google.com/search?q=${encodeURIComponent(searchTerm)}`;

  useEffect(() => {
    if (bookImageCache[book.id]) return; // すでに取得済み・取得中
    let cancelled = false;
    bookImageCache[book.id] = { status: "loading", url: null };

    const cleanTitle = book.title.replace(/\s+/g, " ").trim();
    const query = `${cleanTitle}`;
    const url = `https://www.googleapis.com/books/v1/volumes?q=${encodeURIComponent(query)}&maxResults=3&country=JP`;

    fetch(url)
      .then((res) => (res.ok ? res.json() : Promise.reject(res.status)))
      .then((data) => {
        if (cancelled) return;
        const items = data.items || [];
        const withImage = items.find((it) => it.volumeInfo && it.volumeInfo.imageLinks && it.volumeInfo.imageLinks.thumbnail);
        if (withImage) {
          let thumb = withImage.volumeInfo.imageLinks.thumbnail.replace(/^http:/, "https:");
          bookImageCache[book.id] = { status: "found", url: thumb };
          setImgUrl(thumb);
          setImgStatus("found");
        } else {
          bookImageCache[book.id] = { status: "none", url: null };
          setImgStatus("none");
        }
      })
      .catch(() => {
        if (cancelled) return;
        bookImageCache[book.id] = { status: "none", url: null };
        setImgStatus("none");
      });

    return () => {
      cancelled = true;
    };
  }, [book.id, book.title]);

  return (
    <div
      className="rounded-2xl flex flex-col gap-3 overflow-hidden"
      style={{
        background: "#FFFFFF",
        border: `1px solid ${LINE}`,
        boxShadow: "0 1px 2px rgba(46,36,24,0.04)",
      }}
    >
      {/* 表紙画像エリア */}
      <div
        className="relative flex items-center justify-center"
        style={{
          height: 170,
          background: s.soft,
          borderBottom: `1px solid ${LINE}`,
        }}
      >
        {imgStatus === "found" && imgUrl ? (
          <img
            src={imgUrl}
            alt={`${book.title}の表紙`}
            onError={() => setImgStatus("none")}
            style={{
              maxHeight: "100%",
              maxWidth: "100%",
              objectFit: "contain",
              padding: 12,
            }}
          />
        ) : imgStatus === "loading" ? (
          <div className="flex flex-col items-center gap-1.5" style={{ color: s.color, opacity: 0.5 }}>
            <div
              style={{
                width: 22,
                height: 22,
                border: `2.5px solid ${s.color}40`,
                borderTopColor: s.color,
                borderRadius: "50%",
                animation: "spin 0.8s linear infinite",
              }}
            />
            <span className="text-xs font-bold">画像を検索中</span>
          </div>
        ) : (
          <div className="flex flex-col items-center gap-1.5" style={{ color: s.color, opacity: 0.6 }}>
            <BookOpen size={28} />
            <span className="text-xs font-bold">表紙画像が見つかりません</span>
          </div>
        )}
        {/* 科目バッジ(右上) */}
        <span
          className="absolute top-2 right-2 inline-flex items-center gap-1 text-xs font-bold px-2.5 py-1 rounded-full"
          style={{ background: "#fff", color: s.color, boxShadow: "0 1px 2px rgba(46,36,24,0.08)" }}
        >
          <span>{s.emoji}</span>
          {s.label}
        </span>
      </div>

      {/* テキスト情報 */}
      <div className="px-4 pt-1 pb-4 flex flex-col gap-2">
        <h3
          className="font-bold leading-snug"
          style={{ fontFamily: "'Zen Maru Gothic', sans-serif", fontSize: 15, color: INK }}
        >
          {book.title}
        </h3>
        <p className="text-xs" style={{ color: INK_SOFT }}>
          {book.subjectDetail}
        </p>
        {book.usage && (
          <span
            className="text-xs font-bold px-2 py-0.5 rounded-full self-start"
            style={{ background: u.soft, color: u.color }}
          >
            {book.usage}
          </span>
        )}
        {book.note && (
          <p className="text-xs leading-relaxed" style={{ color: INK_SOFT }}>
            {book.note}
          </p>
        )}

        {/* 検索ボタン */}
        <div className="flex gap-2 mt-2 pt-3" style={{ borderTop: `1px solid ${LINE}` }}>
          <a
            href={amazonUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="flex-1 inline-flex items-center justify-center gap-1 text-xs font-bold py-2 rounded-lg transition-colors"
            style={{ background: "#FFF1E1", color: "#B8553C" }}
          >
            Amazonで見る
          </a>
          <a
            href={googleUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="flex-1 inline-flex items-center justify-center gap-1 text-xs font-bold py-2 rounded-lg transition-colors"
            style={{ background: s.soft, color: s.color }}
          >
            Googleで見る
          </a>
        </div>
      </div>
    </div>
  );
}

