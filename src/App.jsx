/* ルート                                                               */
/* ------------------------------------------------------------------ */
export default function ManabiGymApp() {
  const [activeTab, setActiveTab] = useState("training");

  // 自学自習(training)タブの状態
  const [view, setView] = useState("home");
  const [query, setQuery] = useState("");
  const [activeCategory, setActiveCategory] = useState("all");
  const [activeSituation, setActiveSituation] = useState(null);
  const [activeId, setActiveId] = useState(null);
  const [completed, setCompleted] = useState(new Set());

  // 参考書(books)タブの状態
  const [bookQuery, setBookQuery] = useState("");
  const [activeSubject, setActiveSubject] = useState("all");
  const [activeUsage, setActiveUsage] = useState("all");

  const filtered = useMemo(() => {
    return ARTICLES.filter((a) => {
      // 悩みフィルタが優先
      if (activeSituation) {
        return (a.situations || []).includes(activeSituation);
      }
      const inCategory = activeCategory === "all" || a.category === activeCategory;
      if (!inCategory) return false;
      const q = query.trim().toLowerCase();
      if (!q) return true;
      const haystack = [a.title, a.lead, ...a.tags, CATEGORIES[a.category].label].join(" ").toLowerCase();
      return haystack.includes(q);
    });
  }, [query, activeCategory, activeSituation]);

  const filteredBooks = useMemo(() => {
    return BOOKS.filter((b) => {
      if (activeSubject !== "all" && b.subject !== activeSubject) return false;
      if (activeUsage !== "all" && b.usage !== activeUsage) return false;
      const q = bookQuery.trim().toLowerCase();
      if (!q) return true;
      const haystack = [b.title, b.subjectDetail, b.usage || "", SUBJECT_GROUPS[b.subject].label, b.note || ""]
        .join(" ")
        .toLowerCase();
      return haystack.includes(q);
    });
  }, [bookQuery, activeSubject, activeUsage]);

  const activeArticle = ARTICLES.find((a) => a.id === activeId);

  function openArticle(id) {
    setActiveId(id);
    setView("article");
    window.scrollTo({ top: 0, behavior: "instant" });
  }
  function goHome() {
    setView("home");
  }
  function toggleComplete(id) {
    setCompleted((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  }

  return (
    <div style={{ fontFamily: "'Zen Kaku Gothic New', sans-serif", background: BG, minHeight: "100vh", color: INK }}>
      <style>{`@import url('https://fonts.googleapis.com/css2?family=Zen+Maru+Gothic:wght@500;700;900&family=Zen+Kaku+Gothic+New:wght@400;500;700&display=swap'); @keyframes spin { to { transform: rotate(360deg); } }`}</style>

      {/* 自学自習タブ */}
      {activeTab === "training" && view === "home" && (
        <>
          <TabBar activeTab={activeTab} setActiveTab={setActiveTab} completedCount={completed.size} />
          <HomeView
            query={query}
            setQuery={setQuery}
            activeCategory={activeCategory}
            setActiveCategory={setActiveCategory}
            activeSituation={activeSituation}
            setActiveSituation={setActiveSituation}
            filtered={filtered}
            completed={completed}
            onOpen={openArticle}
            completedCount={completed.size}
          />
        </>
      )}
      {activeTab === "training" && view === "article" && activeArticle && (
        <ArticleView
          article={activeArticle}
          completed={completed.has(activeArticle.id)}
          onBack={goHome}
          onToggleComplete={toggleComplete}
          onOpen={openArticle}
        />
      )}

      {/* 参考書タブ */}
      {activeTab === "books" && (
        <>
          <TabBar activeTab={activeTab} setActiveTab={setActiveTab} completedCount={completed.size} />
          <BooksHomeView
            query={bookQuery}
            setQuery={setBookQuery}
            activeSubject={activeSubject}
            setActiveSubject={setActiveSubject}
            activeUsage={activeUsage}
            setActiveUsage={setActiveUsage}
            filteredBooks={filteredBooks}
          />
        </>
      )}
    </div>
  );
}
